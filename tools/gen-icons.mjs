import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const pack = require("./node_modules/@web3icons/core/dist/index.js");

// chain id -> the icon name in @web3icons. Only the ones that exist; everything
// else falls back to the ticker monogram, which is why this map is explicit
// rather than fuzzy-matched at runtime.
const MAP = {
  bitcoin: "Bitcoin", ethereum: "Ethereum", base: "Base", arbitrum: "ArbitrumOne",
  optimism: "Optimism", polygon: "Polygon", avalanche: "Avalanche", xrpl: "Xrp",
  stellar: "Stellar", tron: "Tron", solana: "Solana", bnb: "BinanceSmartChain",
  ton: "Ton", litecoin: "Litecoin", hedera: "HederaHashgraph", cardano: "Cardano",
  aptos: "Aptos", sui: "Sui", near: "NearProtocol", cosmos: "CosmosHub",
  polkadot: "Polkadot", algorand: "Algorand", injective: "Injective", sei: "SeiNetwork",
  ethereumclassic: "EthereumClassic", linea: "Linea", zksync: "Zksync",
  starknet: "Starknet", scroll: "Scroll", blast: "Blast", mantle: "Mantle",
  ronin: "Ronin", tempo: "Tempo", plasma: "Plasma", hyperliquid: "HyperEvm",
  unichain: "Unichain", worldchain: "World", celo: "Celo", gnosis: "Gnosis",
  monad: "Monad", berachain: "Berachain",
};

const out = {};
const missing = [];
for (const [id, name] of Object.entries(MAP)) {
  const entry = pack[`NetworkMono${name}`];
  const svg = entry?.default;
  if (!svg) { missing.push(`${id} (${name})`); continue; }
  // Keep the geometry, drop the wrapper, and let colour come from the parent so
  // the glyph sits in our palette instead of importing 41 brand colours.
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/fill="(?!none)[^"]*"/g, 'fill="currentColor"')
    .replace(/stroke="(?!none)[^"]*"/g, 'stroke="currentColor"')
    .replace(/\s+/g, " ")
    .trim();
  out[id] = inner;
}

const body = `// GENERATED by tools/gen-icons.mjs from @web3icons/core (MIT). Do not hand-edit.
//
// Monochrome network glyphs, inlined so the site ships no icon dependency and
// makes no request for them. Colour comes from the parent via currentColor, so
// they sit in the palette rather than dragging 41 brand colours onto the page.
// A chain with no glyph here renders its ticker monogram instead.

export const CHAIN_ICON: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("src/content/chainIcons.ts", body);
console.log(`wrote ${Object.keys(out).length} glyphs`);
if (missing.length) console.log("missing:", missing.join(", "));
